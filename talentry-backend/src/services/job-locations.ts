/**
 * Job boards write locations as free text: "Foster City, CA", "Office -
 * Bangalore, India", "AU: Sydney (45 Clarence St)", "Remote - USA". Filtering
 * on those strings exactly is useless, so the Location filter works on regions
 * instead: a job matches a region when any of its location strings matches any
 * of that region's patterns.
 *
 * The patterns are PostgreSQL regular expressions evaluated with `~*`
 * (case-insensitive). `\m` and `\M` are Postgres word boundaries, which is what
 * keeps `\mus\M` from matching "USA" or "Austin", and `ca\M` from matching
 * "Canada".
 *
 * Regions deliberately overlap: "Remote - USA" is both United States and
 * remote, and a job listing several cities belongs to several regions. Counts
 * in the filter menu are therefore per region, not a partition of all jobs.
 */
export interface LocationRegion {
  slug: string;
  label: string;
  patterns: string[];
}

