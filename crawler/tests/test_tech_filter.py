def test_non_technical_titles_are_dropped(title):
    assert is_tech_job(job(title)) is False


def test_occupation_whitelist_keeps_a_job_even_without_a_clear_title():
    assert is_tech_job(job("Member of Technical Staff", occupation="software-engineer")) is True
    assert is_tech_job(job("Member of Technical Staff", occupation=None)) is True
    assert is_tech_job(job("Ninja", occupation="data-engineer")) is True


def test_technology_fallback_needs_a_role_word():
    assert is_tech_job(job("Senior Developer", technologies=["python"])) is True
    assert is_tech_job(job("Senior Engineer", technologies=["aws"])) is True
    assert is_tech_job(job("Ninja", technologies=["python"])) is False


def test_technology_fallback_does_not_override_a_non_tech_title():
    assert is_tech_job(job("Sales Engineer", technologies=["aws"])) is False
    assert is_tech_job(job("Product Manager - AI", technologies=["python"])) is False
    assert is_tech_job(job("Marketing Manager - Data", technologies=["sql"])) is False
